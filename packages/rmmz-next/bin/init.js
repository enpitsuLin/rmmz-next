/* eslint-disable no-console */
import { existsSync } from 'node:fs'
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = fileURLToPath(new URL('../', import.meta.url))
const templateRoot = join(packageRoot, 'templates')
const backupDirectory = '.rmmz-next-backup'

const templateFiles = [
  'js/main.js',
  'js/plugins/RmmzGlobals.js',
  'tsconfig.json',
  'vite.config.ts',
]

const legacyFiles = [
  'js/rmmz_core.js',
  'js/rmmz_managers.js',
  'js/rmmz_objects.js',
  'js/rmmz_scenes.js',
  'js/rmmz_sprites.js',
  'js/rmmz_windows.js',
  'js/libs/pixi.js',
  'js/libs/pako.min.js',
  'js/libs/localforage.min.js',
]

export async function commandInit(dir = '.') {
  const root = resolve(dir)
  const marker = join(root, 'game.rmmzproject')
  if (!existsSync(marker) || !(await readFile(marker, 'utf8')).startsWith('RPGMZ ')) {
    throw new Error(`不是 RPG Maker MZ 工程：${root}`)
  }
  const backupRoot = join(root, backupDirectory)
  if (existsSync(backupRoot)) {
    throw new Error(`工程已有迁移备份，请勿重复初始化：${backupRoot}`)
  }

  const [manifestSource, html, pluginsSource, entry, templateSource, packageSource, ...templates] = await Promise.all([
    readFile(join(root, 'package.json'), 'utf8'),
    readFile(join(root, 'index.html'), 'utf8'),
    readFile(join(root, 'js/plugins.js'), 'utf8'),
    readFile(join(templateRoot, 'entry.html'), 'utf8'),
    readFile(join(templateRoot, 'package.json'), 'utf8'),
    readFile(join(packageRoot, 'package.json'), 'utf8'),
    ...templateFiles.map(file => readFile(join(templateRoot, file), 'utf8')),
  ])

  const mainScript = /<script\s[^>]*\bsrc\s*=\s*["'](?:\.?\/)?js\/main\.js["'][^>]*>\s*<\/script>/i
  if (!mainScript.test(html)) {
    throw new Error('index.html 中未找到 js/main.js 启动入口。')
  }
  const pluginsMatch = /var\s+\$plugins\s*=\s*([\s\S]*)/.exec(pluginsSource)
  const plugins = pluginsMatch && JSON.parse(pluginsMatch[1].trim().replace(/;$/, ''))
  if (!Array.isArray(plugins)) {
    throw new TypeError('js/plugins.js 中未找到有效的 $plugins 配置。')
  }
  const manifest = JSON.parse(manifestSource)
  const template = JSON.parse(templateSource)
  const ownPackage = JSON.parse(packageSource)
  // Unpublished checkouts must link locally instead of requesting a registry version.
  const dependency = ownPackage.private
    ? `link:${relative(root, packageRoot).split(sep).join('/')}`
    : `^${ownPackage.version}`
  const devDependencies = { ...manifest.devDependencies, ...template.devDependencies }
  delete devDependencies['rmmz-next']
  const postinstall = manifest.scripts?.postinstall
  const nextManifest = {
    ...manifest,
    'name': manifest.name ?? 'rmmz-game',
    'version': manifest.version ?? '1.0.0',
    'type': 'module',
    'private': true,
    'main': 'index.html',
    'scripts': {
      ...manifest.scripts,
      ...template.scripts,
      postinstall: postinstall ? `${postinstall} && rmmz-next protect` : 'rmmz-next protect',
    },
    'dependencies': {
      ...manifest.dependencies,
      'rmmz-next': manifest.dependencies?.['rmmz-next'] ?? manifest.devDependencies?.['rmmz-next'] ?? dependency,
    },
    devDependencies,
    'node-remote': manifest['node-remote'] ?? ['http://localhost:*', 'http://127.0.0.1:*'],
  }
  const nextPlugins = [
    {
      name: 'RmmzGlobals',
      status: true,
      description: 'Publishes the engine on globalThis so classic plugins can run.',
      parameters: {},
    },
    ...plugins.filter(plugin => plugin.name !== 'RmmzGlobals'),
  ]
  const ignoreFile = join(root, '.gitignore')
  const ignore = existsSync(ignoreFile) ? await readFile(ignoreFile, 'utf8') : ''
  const ignoreEntries = ['node_modules', 'dist', '.rmmz-dev', backupDirectory]
    .filter(path => !ignore.split(/\r?\n/).includes(path))
  const files = new Map([
    ...templateFiles.map((file, index) => [file, templates[index]]),
    ['package.json', `${JSON.stringify(nextManifest, null, 2)}\n`],
    ['index.html', html.replace(mainScript, () => entry.trimEnd())],
    ['js/plugins.js', `// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n${JSON.stringify(nextPlugins, null, 2)};\n`],
    ['.gitignore', `${ignore.trimEnd()}${ignore.trimEnd() ? '\n' : ''}${ignoreEntries.join('\n')}\n`],
  ])
  const obsoleteFiles = legacyFiles.filter(file => existsSync(join(root, file)))

  // Finish every backup before replacing or removing any original file.
  await mkdir(backupRoot)
  for (const file of [...files.keys(), ...obsoleteFiles]) {
    if (!existsSync(join(root, file)))
      continue
    const backup = join(backupRoot, file)
    await mkdir(dirname(backup), { recursive: true })
    await copyFile(join(root, file), backup)
  }
  for (const [file, content] of files) {
    const target = join(root, file)
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, content)
  }
  for (const file of obsoleteFiles) {
    await rm(join(root, file))
  }

  console.log(`[rmmz] 已初始化 ${root}`)
  console.log(`[rmmz] 原文件备份：${backupRoot}`)
  console.log('[rmmz] 在工程目录运行 pnpm install，然后运行 pnpm dev 或 pnpm dev:server。')
}
